/**
 * Transcription YouTube à partir des sous-titres publics de la vidéo.
 *
 * Aucune clé d'API : on lit la liste `captionTracks` embarquée dans la page de
 * la vidéo, puis on télécharge la piste choisie au format json3. Renvoie null
 * si la vidéo n'a pas de sous-titres ou si YouTube ne répond pas : l'appelant
 * retombe alors sur l'extraction classique de la page.
 */

import { createLogger } from "../utils/logger.js";

const log = createLogger("YouTubeTranscript");

export interface CaptionTrack {
  baseUrl: string;
  languageCode: string;
  /** "asr" = sous-titres générés automatiquement */
  kind?: string;
  name?: { simpleText?: string; runs?: { text: string }[] };
}

export interface YouTubeTranscript {
  title: string;
  author?: string;
  languageCode: string;
  autoGenerated: boolean;
  text: string;
}

/** Identifiant de vidéo depuis une URL youtube.com/watch, youtu.be ou /shorts. */
export function extractVideoId(url: string): string | null {
  const match = url.match(/(?:youtube\.com\/(?:watch\?(?:.*&)?v=|shorts\/|embed\/)|youtu\.be\/)([\w-]{11})/);
  return match ? match[1] : null;
}

/** Extrait un objet JSON équilibré qui commence à `start` (accolade ou crochet). */
function readBalancedJson(text: string, start: number): string | null {
  const open = text[start];
  const close = open === "[" ? "]" : "}";
  let depth = 0;
  let inString = false;
  for (let i = start; i < text.length; i++) {
    const ch = text[i];
    if (inString) {
      if (ch === "\\") i++;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') inString = true;
    else if (ch === open) depth++;
    else if (ch === close && --depth === 0) return text.slice(start, i + 1);
  }
  return null;
}

/** Pistes de sous-titres et métadonnées lues dans le HTML de la page vidéo. */
export function parseWatchPage(html: string): { tracks: CaptionTrack[]; title?: string; author?: string } {
  let tracks: CaptionTrack[] = [];
  const tracksAt = html.indexOf('"captionTracks":');
  if (tracksAt !== -1) {
    const json = readBalancedJson(html, html.indexOf("[", tracksAt));
    if (json) {
      try {
        tracks = (JSON.parse(json) as CaptionTrack[]).filter(t => typeof t.baseUrl === "string");
      } catch { /* JSON inattendu : pas de pistes */ }
    }
  }
  let title: string | undefined;
  let author: string | undefined;
  const detailsAt = html.indexOf('"videoDetails":');
  if (detailsAt !== -1) {
    const json = readBalancedJson(html, html.indexOf("{", detailsAt));
    if (json) {
      try {
        const details = JSON.parse(json) as { title?: string; author?: string };
        title = details.title;
        author = details.author;
      } catch { /* métadonnées absentes : titre par défaut */ }
    }
  }
  return { tracks, title, author };
}

/**
 * Choisit la piste à télécharger : langue préférée d'abord, sous-titres écrits
 * à la main avant les automatiques, puis n'importe quelle piste.
 */
export function pickCaptionTrack(tracks: CaptionTrack[], preferredLanguages: string[] = ["fr", "en"]): CaptionTrack | null {
  if (tracks.length === 0) return null;
  const lang = (t: CaptionTrack) => t.languageCode.toLowerCase().split("-")[0];
  for (const preferred of preferredLanguages) {
    const manual = tracks.find(t => lang(t) === preferred && t.kind !== "asr");
    if (manual) return manual;
    const auto = tracks.find(t => lang(t) === preferred);
    if (auto) return auto;
  }
  return tracks.find(t => t.kind !== "asr") ?? tracks[0];
}

/** Texte d'une piste au format json3, regroupé en paragraphes d'environ 600 caractères. */
export function parseJson3Transcript(json3: { events?: { segs?: { utf8?: string }[] }[] }): string {
  const pieces: string[] = [];
  for (const event of json3.events ?? []) {
    const line = (event.segs ?? []).map(s => s.utf8 ?? "").join("").replace(/\s+/g, " ").trim();
    if (line) pieces.push(line);
  }
  const paragraphs: string[] = [];
  let current = "";
  for (const piece of pieces) {
    current = current ? `${current} ${piece}` : piece;
    if (current.length >= 600 && /[.!?…]$/.test(current)) {
      paragraphs.push(current);
      current = "";
    }
  }
  if (current) paragraphs.push(current);
  return paragraphs.join("\n\n");
}

const BROWSER_HEADERS = {
  "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36",
  "Accept-Language": "fr-FR,fr;q=0.9,en;q=0.8",
  // Évite la page de consentement cookies servie en Europe.
  Cookie: "CONSENT=YES+1",
};

export async function fetchYouTubeTranscript(url: string, preferredLanguages?: string[]): Promise<YouTubeTranscript | null> {
  const videoId = extractVideoId(url);
  if (!videoId) return null;

  try {
    const page = await fetch(`https://www.youtube.com/watch?v=${videoId}&hl=fr`, {
      headers: BROWSER_HEADERS,
      signal: AbortSignal.timeout(15_000),
    });
    if (!page.ok) return null;
    const { tracks, title, author } = parseWatchPage(await page.text());
    const track = pickCaptionTrack(tracks, preferredLanguages);
    if (!track) {
      log.info(`Aucun sous-titre disponible pour la vidéo ${videoId}`);
      return null;
    }

    const captions = await fetch(`${track.baseUrl}&fmt=json3`, {
      headers: BROWSER_HEADERS,
      signal: AbortSignal.timeout(15_000),
    });
    if (!captions.ok) return null;
    const text = parseJson3Transcript(await captions.json());
    if (!text.trim()) return null;

    return {
      title: title || `Vidéo YouTube ${videoId}`,
      author,
      languageCode: track.languageCode,
      autoGenerated: track.kind === "asr",
      text,
    };
  } catch (e: any) {
    log.warn(`Transcription YouTube indisponible (${videoId}) : ${e?.message || e}`);
    return null;
  }
}
